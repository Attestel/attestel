"""The Python half of the cross-language accounting guarantee.

Go and Python cannot share code; they share `testdata/accounting/*.json`. Those files state the
accounting atom of docs/PAPER_EXECUTION_CONTRACT.md §5.1 — positions, ret_next and cost_bps in,
net/equity/totalReturn/mean/std/trade-count out — and BOTH implementations are held to them:

  * here, against `backtest.net_returns` and `backtest.run_backtest`;
  * in `paper/accounting_fixtures_test.go`, against the live ledger's own fills and marks.

The expected numbers were NOT generated by this module. A fixture produced by the code under test
enshrines that code's bugs as truth, so they were computed from the formula as the contract states
it, and `flat-long-flat.json` carries a `handComputation` block working the whole scenario out in
arithmetic anybody can check by eye. If a fixture and this module disagree, the contract decides
which one moved.

Run:  cd services/prediction && ./.venv/bin/python -m pytest -q tests/test_accounting_fixtures.py
"""
from __future__ import annotations

import json
import math
import pathlib

import numpy as np
import pytest

from app.backtest import net_returns, run_backtest

# services/prediction/tests/ -> services/prediction -> services -> repo root
FIXTURE_DIR = pathlib.Path(__file__).resolve().parents[3] / "testdata" / "accounting"


def _fixtures() -> list[pathlib.Path]:
    return sorted(FIXTURE_DIR.glob("*.json"))


def _load(path: pathlib.Path) -> dict:
    with open(path) as f:
        return json.load(f)


def _ids(paths: list[pathlib.Path]) -> list[str]:
    return [p.stem for p in paths]


def test_the_fixture_directory_exists_and_is_not_empty():
    """A silently-empty parametrization is a suite that passes by testing nothing."""
    assert FIXTURE_DIR.is_dir(), f"missing fixture directory {FIXTURE_DIR}"
    assert len(_fixtures()) >= 5, "the contract requires at least five accounting scenarios"


@pytest.mark.parametrize("path", _fixtures(), ids=_ids(_fixtures()))
def test_net_returns_matches_the_fixture(path: pathlib.Path):
    fx = _load(path)
    inp, exp = fx["inputs"], fx["expected"]
    tol = float(fx.get("tolerance", 1e-9))

    net, entries, _active = net_returns(
        np.array(inp["retNext"], dtype=float),
        np.array(inp["positions"], dtype=float),
        float(inp["costBps"]),
    )

    assert len(net) == len(exp["net"])
    for i, (got, want) in enumerate(zip(net, exp["net"])):
        assert abs(float(got) - float(want)) < tol, f"net[{i}] {got} != {want}"

    # numTrades is a COUNT OF EPISODES, not of bars held (contract §1.2). The fixtures include a
    # multi-bar hold precisely so an implementation that counted held bars would fail here.
    assert int(entries.sum()) == int(exp["numTrades"])

    # Equity compounds the atom: cumprod(1 + net).
    equity = np.cumprod(1.0 + net)
    for i, (got, want) in enumerate(zip(equity, exp["equity"])):
        assert abs(float(got) - float(want)) < tol, f"equity[{i}] {got} != {want}"

    assert abs(float(equity[-1] - 1.0) - float(exp["totalReturn"])) < tol

    mean = float(net.mean())
    std = float(net.std(ddof=0))
    assert abs(mean - float(exp["mean"])) < tol
    assert abs(std - float(exp["std"])) < tol

    # Turnover is served in the fixture so the Go side can check the same thing against its FILLS
    # (one fill per unit of turnover). Assert it here too, so the two halves cannot drift.
    prev = np.concatenate([[0.0], np.asarray(inp["positions"], dtype=float)[:-1]])
    turnover = np.abs(np.asarray(inp["positions"], dtype=float) - prev)
    for i, (got, want) in enumerate(zip(turnover, exp["turnover"])):
        assert abs(float(got) - float(want)) < tol, f"turnover[{i}] {got} != {want}"


@pytest.mark.parametrize("path", _fixtures(), ids=_ids(_fixtures()))
def test_run_backtest_reports_the_same_numbers(path: pathlib.Path):
    """The gated report is built on the same atom, so the fields it rounds must still agree."""
    fx = _load(path)
    inp, exp = fx["inputs"], fx["expected"]

    rep = run_backtest(
        np.array(inp["retNext"], dtype=float),
        np.array(inp["positions"], dtype=float),
        float(inp["costBps"]),
        timeframe=inp.get("timeframe", "1D"),
    )
    # run_backtest rounds: expectancy to 6dp, totalReturn to 4dp.
    assert abs(rep["expectancy"] - float(exp["mean"])) < 1e-6
    assert abs(rep["totalReturn"] - float(exp["totalReturn"])) < 1e-4
    assert rep["numTrades"] == int(exp["numTrades"])


def test_the_hand_computed_scenario_is_present_and_self_consistent():
    """One scenario must be verifiable WITHOUT running either implementation.

    Its `handComputation` block is prose, so it cannot be asserted mechanically — but the scenario
    it describes can, from the numbers written into that block by hand.
    """
    hand = [p for p in _fixtures() if "handComputation" in _load(p)]
    assert hand, "no fixture carries a hand-computed derivation — both implementations could be wrong together"

    fx = _load(hand[0])
    assert fx["name"] == "flat-long-flat"
    # Transcribed from the handComputation block, not from any code:
    assert fx["expected"]["net"] == [0.0, 0.19, -0.1, -0.01]
    assert fx["expected"]["equity"] == [1.0, 1.19, 1.071, 1.06029]
    assert fx["expected"]["numTrades"] == 1
    assert abs(fx["expected"]["mean"] - 0.02) < 1e-12
    assert abs(fx["expected"]["std"] - math.sqrt(0.01115)) < 1e-9
